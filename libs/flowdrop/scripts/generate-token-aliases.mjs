#!/usr/bin/env node
/**
 * Regenerates src/lib/styles/tokenAliases.ts from tokens.css + base.css.
 *   pnpm run generate:token-aliases
 * tests/unit/styles/tokenAliases.test.ts fails when the checked-in file is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  buildAliasMaps,
  renderDarkAliasBlock,
  stripGeneratedRegion,
  DARK_ALIAS_BEGIN,
  DARK_ALIAS_END
} from './parse-token-aliases.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const styles = resolve(root, 'src/lib/styles');

export function render() {
  const maps = buildAliasMaps(
    ['tokens.css', 'base.css'].map((f) =>
      stripGeneratedRegion(readFileSync(resolve(styles, f), 'utf8'))
    )
  );
  return `/**
 * GENERATED by scripts/generate-token-aliases.mjs from styles/tokens.css and
 * styles/base.css. Do not edit by hand; run \`pnpm run generate:token-aliases\`.
 *
 * Alias tokens: declarations whose value reads another --fd-* token. A custom
 * property holding var() is resolved where it is declared, so a skin scoped to
 * an editor root must redeclare the aliases that depend on the tokens it sets.
 * Keys omit the --fd- prefix.
 */

/** Light/base aliases (:root). */
export const LIGHT_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(maps.light, null, 2)};

/** Dark overrides ([data-theme='dark']): aliases, plus literal dark values of light aliases. */
export const DARK_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(maps.dark, null, 2)};
`;
}

/** tokens.css with its generated dark-alias block refreshed (appended on first run). */
export function renderTokensCss() {
  const tokens = readFileSync(resolve(styles, 'tokens.css'), 'utf8');
  const base = readFileSync(resolve(styles, 'base.css'), 'utf8');
  const block = renderDarkAliasBlock([tokens, base]);
  const a = tokens.indexOf(DARK_ALIAS_BEGIN);
  if (a < 0) return `${tokens.replace(/\n*$/, '\n')}\n${block}\n`;
  const b = tokens.indexOf(DARK_ALIAS_END) + DARK_ALIAS_END.length;
  return tokens.slice(0, a) + block + tokens.slice(b);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(styles, 'tokenAliases.ts'), render());
  console.log('wrote src/lib/styles/tokenAliases.ts');
  writeFileSync(resolve(styles, 'tokens.css'), renderTokensCss());
  console.log('wrote the generated dark-alias block in src/lib/styles/tokens.css');
}
